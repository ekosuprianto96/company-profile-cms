<h2 class="sec">Lalu di mana mengatur beranda?</h2>
<p>
    Pengaturan <b>isi dan urutan</b> beranda aplikasi dilakukan di modul <b>Section Home</b> (lihat bab sebelumnya) —
    di sanalah admin membuat blok konten dan menyusun urutannya. Home Layout tidak menggantikan atau menduplikasi fungsi itu.
</p>

