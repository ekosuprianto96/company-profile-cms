<p>
    Modul <b>Inspire (Inspirasi)</b> mengelola artikel/konten inspirasi yang tampil di aplikasi — misalnya tips, ide interior,
    atau cerita renovasi. Konten ini juga bisa dijadikan sumber section di beranda (lihat bab Section Home).
</p>

<h2 class="sec">Halaman daftar</h2>
<p>Tabel menampilkan: <b>Cover</b>, <b>Judul</b> (+ ringkasan), <b>Kategori</b>, <b>Featured</b>, <b>Status</b> (Publish/Unpublish), <b>Meta</b> (waktu baca &amp; urutan), dan <b>Diperbarui oleh</b>. Pencarian bekerja pada judul, kategori, dan nama pengubah.</p>

<h2 class="sec">Menambah / mengubah artikel</h2>
<ol class="steps">
    <li>Klik <b>Tambah Inspire</b> (atau Edit) — membuka halaman formulir.</li>
    <li>Isi <b>Judul</b>, <b>Kategori</b>, ringkasan, dan <b>Konten</b> (editor teks kaya — bisa sisip gambar).</li>
    <li>Unggah <b>Cover</b> (gambar, maks. 2 MB), pilih <b>warna aksen</b>, isi <b>waktu baca</b> (menit) dan <b>urutan</b>.</li>
    <li>Atur <b>Featured</b> (Ya/Tidak) dan <b>Status</b> (Publish/Unpublish), lalu simpan.</li>
</ol>

<table class="tbl">
    <tr><th style="width:150px;">Field</th><th>Keterangan</th></tr>
    <tr><td><b>Featured</b></td><td>Artikel unggulan naik ke atas daftar di aplikasi.</td></tr>
    <tr><td><b>Status</b></td><td><b>Publish</b> = tampil di aplikasi; <b>Unpublish</b> = disembunyikan. Default saat simpan adalah <b>Publish</b>.</td></tr>
    <tr><td><b>Waktu baca</b></td><td>Perkiraan menit membaca (1–60), tampil sebagai info di artikel.</td></tr>
</table>

<div class="box note">
    <span class="bt">Kategori berupa teks bebas</span>
    Kolom Kategori diketik bebas (bukan pilihan tetap). Agar rapi &amp; konsisten, <b>samakan penulisannya</b> (mis. selalu
    "Interior", bukan kadang "interior") — salah ketik akan dianggap kategori baru.
</div>
<div class="box warn">
    <span class="bt">Mengubah judul mengubah alamat artikel</span>
    Alamat (slug) artikel dibuat otomatis dari judul. Mengganti judul akan <b>mengubah slug</b>, sehingga tautan lama
    ke artikel itu bisa tidak berlaku. Hindari sering mengganti judul artikel yang sudah tayang.
</div>
