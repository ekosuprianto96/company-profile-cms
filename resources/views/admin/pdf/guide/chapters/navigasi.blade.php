<p>
    Bab ini menjelaskan cara <b>masuk ke dashboard</b>, mengenali <b>bagian-bagian layar</b>, dan memahami
    <b>konsep dasar</b> yang berlaku di semua modul. Pahami bab ini lebih dulu sebelum ke modul lain.
</p>

<h2 class="sec">1. Masuk ke Dashboard (Login)</h2>
<ol class="steps">
    <li>Buka alamat dashboard admin di browser, lalu tambahkan <code>/admin/login</code> di belakangnya.</li>
    <li>Masukkan <b>email</b> dan <b>kata sandi</b> akun admin Anda.</li>
    <li>Klik <b>Masuk</b>. Jika benar, Anda diarahkan ke halaman <b>Beranda</b> dashboard.</li>
</ol>

<div class="box warn">
    <span class="bt">Jaga kerahasiaan akun</span>
    Jangan bagikan email &amp; kata sandi admin kepada siapa pun. Setiap tindakan di dashboard tercatat atas nama akun yang login.
</div>

<div class="box note">
    <span class="bt">Lupa kata sandi?</span>
    Hubungi administrator sistem (pemilik akun tertinggi) untuk mengatur ulang kata sandi Anda melalui modul
    <span class="path" style="margin:0;">Pengguna</span>. Cara pengelolaan pengguna dibahas pada bagian Sistem &amp; Akses.
</div>

<h2 class="sec">2. Mengenal Tampilan Dashboard</h2>
<p>Setelah login, layar terbagi menjadi tiga area utama:</p>

<table class="tbl">
    <tr><th style="width:150px;">Area</th><th>Fungsi</th></tr>
    <tr><td><b>Sidebar (kiri)</b></td><td>Daftar menu semua modul. Klik untuk berpindah halaman. Berisi <b>Beranda</b>, <b>Mobile App</b>, dan menu modul website lainnya.</td></tr>
    <tr><td><b>Topbar (atas)</b></td><td>Menampilkan akun yang sedang login, notifikasi, dan tombol keluar (logout).</td></tr>
    <tr><td><b>Area konten (tengah)</b></td><td>Isi halaman modul yang sedang dibuka — tabel data, formulir, atau tombol aksi.</td></tr>
</table>

<h3 class="sub">Dua kelompok modul</h3>
<p>Menu di dashboard terbagi menjadi dua kelompok besar:</p>
<ul>
    <li><b>Mobile App</b> — semua yang tampil di <b>aplikasi pelanggan</b>: kategori, layanan, produk, voucher, notifikasi, chat, tampilan beranda aplikasi, dan pengaturan aplikasi. Klik menu <span class="path" style="margin:0;">Mobile App</span> untuk membuka grid berisi seluruh modul mobile.</li>
    <li><b>Website / CMS</b> — konten situs web: halaman, menu, blog, banner, galeri, dan sejenisnya. Muncul sebagai menu terpisah di sidebar.</li>
</ul>

<h2 class="sec">3. Konsep yang Berlaku di Semua Modul</h2>
<p>Sebagian besar modul memakai pola kerja yang sama. Menguasainya sekali berarti bisa dipakai di mana saja:</p>

<table class="tbl">
    <tr><th style="width:150px;">Istilah / Tombol</th><th>Arti</th></tr>
    <tr><td><b>Daftar (List)</b></td><td>Halaman utama modul berisi tabel data yang sudah ada. Biasanya dilengkapi kolom pencarian dan filter.</td></tr>
    <tr><td><b>Tambah / Buat</b></td><td>Tombol untuk membuat data baru, membuka formulir kosong.</td></tr>
    <tr><td><b>Edit / Ubah</b></td><td>Ikon pensil pada baris data untuk mengubah data yang sudah ada.</td></tr>
    <tr><td><b>Hapus</b></td><td>Ikon tempat sampah untuk menghapus data. Biasanya muncul konfirmasi terlebih dahulu.</td></tr>
    <tr><td><b>Simpan</b></td><td>Menyimpan perubahan pada formulir. Wajib diklik agar data tersimpan.</td></tr>
    <tr><td><b>Aktif / Nonaktif</b></td><td>Sakelar (toggle) untuk menyalakan atau mematikan sebuah data tanpa menghapusnya.</td></tr>
    <tr><td><b>Status</b></td><td>Label warna yang menunjukkan keadaan data (mis. menunggu, disetujui, selesai).</td></tr>
</table>

<div class="box tip">
    <span class="bt">Selalu klik Simpan</span>
    Perubahan pada formulir hanya tersimpan setelah tombol <b>Simpan</b> ditekan. Berpindah halaman tanpa menyimpan akan membuang perubahan.
</div>

<h3 class="sub">Kolom bertanda wajib</h3>
<p>
    Kolom yang wajib diisi biasanya ditandai. Jika ada isian yang belum benar, sistem menampilkan
    <b>pesan berwarna merah</b> di bawah kolom tersebut saat menyimpan. Perbaiki lalu simpan ulang.
</p>

<h2 class="sec">4. Keluar (Logout)</h2>
<p>
    Selalu keluar dari akun setelah selesai, terutama pada komputer bersama. Klik nama/akun Anda di <b>Topbar</b>
    kanan atas, lalu pilih <b>Keluar</b>.
</p>

<div class="box note">
    <span class="bt">Langkah selanjutnya</span>
    Anda kini siap menjelajah tiap modul. Bagian-bagian berikutnya membahas setiap modul secara rinci —
    mulai dari modul Mobile App inti hingga pengaturan sistem.
</div>
