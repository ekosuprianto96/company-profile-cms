<p>
    <span class="path">Sidebar → Mobile App → Penilaian Produk</span>
</p>
<p>
    Modul <b>Penilaian Produk</b> menampilkan <b>ulasan &amp; rating</b> yang diberikan pembeli terhadap produk.
    Berguna untuk memantau kepuasan pelanggan dan kualitas produk.
</p>

<div class="box warn">
    <span class="bt">Modul ini hanya untuk memantau (read-only)</span>
    Admin <b>tidak dapat</b> menyetujui, menolak, menghapus, atau membalas ulasan dari sini — tidak ada fitur moderasi.
    Semua ulasan yang dikirim pembeli otomatis tampil.
</div>

<h2 class="sec">Halaman daftar</h2>
<p>Kolom yang ditampilkan:</p>
<table class="tbl">
    <tr><th style="width:180px;">Kolom</th><th>Arti</th></tr>
    <tr><td><b>Produk &amp; Pembeli</b></td><td>Nama produk dan nama pengguna yang mengulas.</td></tr>
    <tr><td><b>Rating</b></td><td>Bintang 1–5 (bintang penuh, tanpa setengah).</td></tr>
    <tr><td><b>Komentar</b></td><td>Isi ulasan (dipotong; "Tanpa komentar" bila kosong).</td></tr>
    <tr><td><b>Tanggal</b></td><td>Waktu ulasan dibuat.</td></tr>
    <tr><td><b>Detail</b></td><td>Tombol membuka rincian ulasan lengkap.</td></tr>
</table>
<p>Tersedia dropdown <b>saring berdasarkan produk</b> (hanya menampilkan produk yang sudah punya ulasan, lengkap dengan rata-rata bintang dan jumlah ulasannya).</p>

<h2 class="sec">Detail ulasan</h2>
<p>Klik <b>Detail</b> untuk melihat: gambar &amp; nama produk, <b>rata-rata rating</b> produk beserta jumlah ulasan, bintang ulasan ini, komentar, nama pembeli, nomor pesanan, dan tanggal.</p>

<div class="box note">
    <span class="bt">Rata-rata tersimpan di produk</span>
    Rata-rata bintang dan jumlah ulasan sebuah produk disimpan pada data produk dan otomatis diperbarui saat ada ulasan baru,
    sehingga cepat ditampilkan di aplikasi.
</div>
