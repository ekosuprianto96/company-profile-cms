<p>
    <b>Live Chat</b> adalah ruang percakapan <b>real-time</b> antara admin dan pengguna aplikasi. Dipakai untuk menjawab
    pertanyaan, membahas order, atau membantu pelanggan. Pesan baru masuk otomatis tanpa perlu me-refresh halaman.
</p>

<h2 class="sec">Tampilan</h2>
<p>Layar terbagi dua: <b>daftar percakapan</b> (kiri) dan <b>ruang chat</b> (kanan).</p>
<ul>
    <li>Daftar diurutkan dari percakapan dengan pesan terbaru. Tiap item menampilkan nama pengguna, subjek (kode order bila chat berasal dari order), cuplikan pesan terakhir, waktu, dan <b>badge merah</b> berisi jumlah pesan belum dibaca.</li>
    <li>Kotak pencarian mencari berdasarkan <b>nama/kontak pengguna</b> atau <b>kode order</b>.</li>
    <li>Indikator "Realtime" menandakan koneksi langsung aktif.</li>
</ul>

<h2 class="sec">Membalas pesan</h2>
<ol class="steps">
    <li>Klik salah satu percakapan di daftar kiri. Pesan otomatis ditandai sudah dibaca.</li>
    <li>Ketik balasan di kolom bawah. Anda bisa melampirkan hingga <b>6 berkas</b> (gambar JPG/PNG/WebP/GIF atau PDF, maks. 10 MB per berkas).</li>
    <li>Klik kirim. Pesan langsung sampai ke aplikasi pengguna + pengguna menerima notifikasi.</li>
</ol>

<div class="box note">
    <span class="bt">Satu percakapan per konteks</span>
    Chat yang berasal dari sebuah order selalu mengarah ke percakapan yang sama antara admin dan pengguna itu.
    Membuka <b>Chat</b> dari detail Order Layanan/Order Produk otomatis membuka (atau membuat) percakapan yang tepat,
    lengkap dengan tombol <b>Detail Order</b> di dalamnya.
</div>

<div class="box tip">
    <span class="bt">Admin penanggung jawab otomatis</span>
    Admin pertama yang membuka/membalas sebuah percakapan otomatis menjadi penanggung jawabnya. Tidak ada tombol
    tutup/hapus percakapan — percakapan tetap tersimpan sebagai riwayat.
</div>

<div class="box warn">
    <span class="bt">Wajib isi pesan atau lampiran</span>
    Balasan tidak bisa dikirim kosong — minimal ada teks atau satu lampiran. Bila muncul "Tulis pesan atau lampirkan media",
    isi salah satunya lalu kirim ulang.
</div>
