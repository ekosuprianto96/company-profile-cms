<h2 class="sec">Struktur dokumen</h2>
<p>
    Panduan disusun bertahap (per fase) dan dikelompokkan per bagian. Setiap bab membahas satu modul:
    <b>apa fungsinya</b>, <b>di mana lokasinya</b>, dan <b>langkah penggunaannya</b>. Gunakan Daftar Isi
    di halaman sebelumnya untuk melompat ke modul yang dibutuhkan.
</p>

