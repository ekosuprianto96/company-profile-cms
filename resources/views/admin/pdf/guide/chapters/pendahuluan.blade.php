<p>
    Dokumen ini adalah <b>buku panduan (log book)</b> resmi penggunaan dashboard admin {{ $appName }}.
    Tujuannya agar admin — baik yang baru maupun yang sudah berpengalaman — dapat memahami
    <b>cara mengatur dan menggunakan setiap modul serta fitur</b> yang tersedia, tanpa perlu bertanya berulang.
</p>

<h2 class="sec">Untuk siapa panduan ini</h2>
<ul>
    <li><b>Admin operasional</b> — mengelola pengajuan layanan, pesanan produk, dan chat pelanggan setiap hari.</li>
    <li><b>Admin konten</b> — mengatur kategori, produk, voucher, promosi, dan tampilan aplikasi mobile.</li>
    <li><b>Administrator sistem</b> — mengatur pengguna admin, hak akses (role), dan pengaturan aplikasi.</li>
</ul>

<h2 class="sec">Cara membaca panduan</h2>
<p>Agar mudah diikuti, panduan memakai penanda visual yang konsisten:</p>

<p>
    <span class="path">Menu Utama → Submenu</span><br>
    Menunjukkan <b>lokasi fitur</b> di dashboard. Ikuti jalur ini pada menu di layar Anda.
</p>

