<p>
    <span class="path">Mobile App → Overview → kartu "Support Contacts"</span>
</p>
<p>
    Modul <b>Support Contacts</b> mengelola daftar <b>kontak bantuan</b> yang tampil di aplikasi — WhatsApp, telepon,
    email, Instagram, atau tautan lain — agar pengguna mudah menghubungi tim.
</p>

<h2 class="sec">Halaman daftar</h2>
<p>Tabel menampilkan: <b>Contact</b> (label + isi), <b>Type</b>, <b>Sort Order</b>, dan <b>Status</b> (Aktif/Nonaktif).</p>

<h2 class="sec">Menambah kontak</h2>
<ol class="steps">
    <li>Klik tombol tambah, isi form pada modal.</li>
    <li>Pilih <b>Type</b>: WhatsApp, Email, Telepon, Instagram, atau Lainnya.</li>
    <li>Isi <b>Label</b> (nama tampil, mis. "CS WhatsApp") dan <b>Value</b> (nomor/email/username).</li>
    <li>Atur <b>Urutan</b> dan status <b>Aktif</b>, lalu simpan.</li>
</ol>

<h2 class="sec">Cara mengisi Value tiap tipe</h2>
<table class="tbl">
    <tr><th style="width:120px;">Type</th><th>Isi Value</th></tr>
    <tr><td><b>WhatsApp</b></td><td>Nomor HP (jadi tautan wa.me otomatis).</td></tr>
    <tr><td><b>Email</b></td><td>Alamat email (jadi tautan email).</td></tr>
    <tr><td><b>Telepon</b></td><td>Nomor telepon (jadi tautan panggilan).</td></tr>
    <tr><td><b>Instagram</b></td><td>Username <b>tanpa tanda @</b>.</td></tr>
    <tr><td><b>Lainnya</b></td><td>Harus berupa <b>URL lengkap</b> (diawali <code>http</code>) agar dapat diklik.</td></tr>
</table>

<div class="box warn">
    <span class="bt">Status Aktif wajib dipilih</span>
    Kolom status harus diisi (Aktif / Tidak Aktif). Hanya kontak <b>Aktif</b> yang tampil di aplikasi — nonaktifkan
    daripada menghapus bila hanya ingin menyembunyikan sementara.
</div>
