<p>
    Halaman <b>Overview</b> adalah <b>pusat navigasi</b> untuk semua modul yang mengatur aplikasi mobile
    ({{ $appName }}). Dari sini admin melihat ringkasan singkat kondisi aplikasi dan berpindah ke modul mana pun.
</p>

<h2 class="sec">Ringkasan angka (statistik)</h2>
<p>Di bagian atas terdapat empat kartu angka untuk memantau kondisi cepat:</p>
<table class="tbl">
    <tr><th style="width:180px;">Kartu</th><th>Arti</th></tr>
    <tr><td><b>Total Mobile Users</b></td><td>Jumlah seluruh pengguna aplikasi yang terdaftar.</td></tr>
    <tr><td><b>User Terverifikasi</b></td><td>Pengguna yang sudah memverifikasi email atau nomor HP-nya.</td></tr>
    <tr><td><b>OTP Pending/Sent</b></td><td>Jumlah kode OTP yang sedang menunggu / baru terkirim.</td></tr>
    <tr><td><b>Token Aktif</b></td><td>Jumlah sesi login aktif di perangkat. <i>Catatan: satu pengguna bisa punya beberapa sesi, jadi angka ini bukan jumlah pengguna unik.</i></td></tr>
</table>

<h2 class="sec">Menjelajah modul</h2>
<p>Di bawah statistik terdapat grid kartu berisi seluruh modul mobile. Cara pakai:</p>
<ol class="steps">
    <li>Ketik di kolom <b>"Cari menu…"</b> untuk menyaring kartu berdasarkan nama/keterangan.</li>
    <li>Klik ikon <b>Grid / List</b> untuk mengubah tampilan (pilihan Anda tersimpan otomatis di browser).</li>
    <li>Klik kartu modul untuk membukanya. Tombol pintas <b>"Kelola Pengguna"</b> di atas langsung menuju modul Users.</li>
</ol>

<div class="box note">
    <span class="bt">Kartu yang muncul tergantung hak akses</span>
    Sebagian modul (mis. Kategori, Proposal, Voucher, Produk, Promosi) hanya tampil bila akun Anda punya izin untuk modul tersebut.
    Jika sebuah kartu tidak terlihat, kemungkinan role Anda belum diberi akses — hubungi administrator sistem.
</div>
