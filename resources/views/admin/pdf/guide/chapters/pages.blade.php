<p>
    <span class="path">Sidebar → Tampilan Website → (nama halaman)</span>
</p>
<p>
    Modul <b>Pages</b> dipakai untuk <b>mengatur isi &amp; SEO tiap halaman situs web</b> yang sudah ada —
    seperti Beranda, Layanan, Tentang Kami, Blog, Kontak, dan Galeri. Ini bukan pembuat halaman bebas:
    admin <b>mengedit</b> halaman yang sudah ditetapkan, bukan membuat/menghapus halaman baru.
</p>

<h2 class="sec">Bentuk halaman: tab</h2>
<p>Saat membuka sebuah halaman, pengaturannya tersaji dalam beberapa tab (muncul sesuai yang tersedia):</p>
<table class="tbl">
    <tr><th style="width:150px;">Tab</th><th>Fungsi</th></tr>
    <tr><td><b>Meta (SEO)</b></td><td>Judul meta, deskripsi, kata kunci, dan gambar untuk mesin pencari &amp; berbagi tautan.</td></tr>
    <tr><td><b>Sections</b></td><td>Isi bagian-bagian halaman (mis. hero banner, tentang kami, daftar layanan) — diedit lewat jendela per bagian.</td></tr>
    <tr><td><b>Styles / Scripts</b></td><td>Kode CSS/JS tambahan untuk halaman (untuk pengguna teknis).</td></tr>
    <tr><td><b>Custom Meta</b></td><td>Tag meta kustom mentah, bila diperlukan.</td></tr>
</table>

<h2 class="sec">Cara mengedit</h2>
<ol class="steps">
    <li>Buka halaman yang ingin diatur dari menu <b>Tampilan Website</b>.</li>
    <li>Pilih tab yang sesuai (mis. <b>Meta</b> untuk SEO, atau <b>Sections</b> untuk isi).</li>
    <li>Untuk <b>Sections</b>, klik bagian yang ingin diubah — jendela editnya terbuka; ubah teks/gambar/tombol.</li>
    <li>Klik <b>Simpan</b> pada tab/bagian tersebut. Penyimpanan dilakukan <b>per tab</b>.</li>
</ol>

<div class="box warn">
    <span class="bt">Simpan per tab</span>
    Tiap tab disimpan sendiri-sendiri. Setelah mengubah isi sebuah tab, klik simpan di tab itu sebelum berpindah,
    agar perubahan tidak hilang.
</div>
<div class="box note">
    <span class="bt">Bukan pembuat halaman</span>
    Anda tidak bisa menambah atau menghapus halaman dari sini, juga tidak ada status publish/draft di level halaman.
    Modul ini khusus <b>menyunting</b> halaman yang sudah didefinisikan. Tab Styles/Scripts sebaiknya hanya diubah oleh
    pengguna yang paham kode.
</div>
