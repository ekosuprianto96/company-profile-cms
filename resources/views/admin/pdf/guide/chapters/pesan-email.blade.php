<p>
    <span class="path">Sidebar → Marketing → Pesan Email</span>
</p>
<p>
    Modul <b>Pesan Email</b> menggabungkan beberapa fungsi terkait email: <b>kotak masuk</b> dari form kontak situs web,
    <b>membalas</b> pesan, mengelola <b>daftar kontak</b>, mengirim <b>email massal</b>, dan mengatur <b>SMTP</b> (server pengirim email).
</p>

<h2 class="sec">Kotak masuk (pesan dari form kontak)</h2>
<p>Halaman utama menampilkan daftar pesan yang dikirim pengunjung lewat form kontak website. Kolom: <b>Nama</b>, <b>Email</b>, <b>Subject</b>, dan <b>Status</b> (Sudah/Belum Dibaca).</p>
<ol class="steps">
    <li>Klik sebuah pesan untuk membuka detailnya — pesan otomatis ditandai <b>sudah dibaca</b>.</li>
    <li>Klik <b>Balas</b> untuk mengirim jawaban. Balasan dikirim ke email pengirim dan tersimpan sebagai riwayat percakapan.</li>
    <li>Pesan yang tak diperlukan dapat dihapus (dengan konfirmasi).</li>
</ol>

<h2 class="sec">Kontak & email massal</h2>
<ul>
    <li><b>Daftar Kontak</b> — kelola kontak pelanggan (nama, email, telepon, alamat). Bisa <b>impor</b> dari Excel/CSV dan <b>ekspor</b>.</li>
    <li><b>Kirim Pesan Massal</b> — susun satu email lalu kirim ke banyak kontak sekaligus.</li>
    <li><b>Riwayat Email Keluar</b> — memantau status pengiriman: <b>Pending</b>, <b>Dikirim</b>, atau <b>Gagal</b>.</li>
</ul>

<h2 class="sec">Pengaturan SMTP</h2>
<p>Halaman <b>Pengaturan</b> berisi konfigurasi server email: <b>Host</b>, <b>Port</b>, <b>Username</b>, <b>Password</b>, dan <b>alamat pengirim</b>. Ini menentukan dari mana email sistem &amp; balasan dikirim.</p>

<div class="box warn">
    <span class="bt">Ubah SMTP dengan hati-hati</span>
    Salah mengisi SMTP membuat email <b>gagal terkirim</b>. Jangan mengubah alamat "dari" tanpa konfigurasi SMTP yang valid.
    Bila ragu, minta bantuan tim teknis. Perhatikan juga: kata sandi SMTP ditampilkan terbuka di layar — buka halaman ini di tempat aman.
</div>
<div class="box note">
    <span class="bt">Alamat balasan</span>
    Alamat pengirim untuk balasan diambil dari data kontak di halaman "Kontak Kami". Pastikan data itu terisi agar fitur balas berfungsi.
</div>
