<p>
    Halaman <b>Profil</b> berisi data <b>akun admin Anda sendiri</b> yang sedang login. Di sini Anda mengubah identitas,
    foto, dan kata sandi.
</p>

<h2 class="sec">Yang bisa diubah</h2>
<ul>
    <li><b>Foto profil</b> — unggah avatar akun.</li>
    <li><b>Identitas</b> — nama, email, nomor telepon, No. KTP, NIP, tanggal lahir, dan alamat.</li>
    <li><b>Kata sandi</b> — isi hanya bila ingin mengganti; kosongkan bila tidak.</li>
</ul>

<h2 class="sec">Cara mengubah</h2>
<ol class="steps">
    <li>Buka menu akun (foto) di pojok kanan atas, pilih <b>My Profile</b>.</li>
    <li>Perbarui data pada form, atau unggah foto baru.</li>
    <li>Untuk ganti sandi, isi kolom <b>Password</b> (min. 6 karakter). Biarkan kosong bila tak ingin mengubahnya.</li>
    <li>Klik <b>Simpan</b>.</li>
</ol>

<div class="box warn">
    <span class="bt">Semua kolom identitas wajib terisi saat menyimpan</span>
    Kolom seperti <b>KTP (tepat 16 digit)</b>, <b>NIP</b>, telepon, tanggal lahir, dan alamat <b>harus terisi</b> agar
    penyimpanan berhasil — meski Anda hanya ingin mengganti nama atau kata sandi. Lengkapi semuanya sebelum menyimpan.
</div>
<div class="box note">
    <span class="bt">Peran (role) tidak bisa diubah sendiri</span>
    Anda tidak dapat mengganti role akun Anda sendiri dari halaman profil. Perubahan role dilakukan administrator melalui
    modul <b>User</b> (lihat bab User).
</div>
