<p>
    <span class="path">Mobile App → Overview → kartu "App Content"</span>
</p>
<p>
    Modul <b>App Content</b> mengatur dua <b>halaman statis</b> di aplikasi: <b>Tentang Aplikasi</b> dan
    <b>Syarat &amp; Ketentuan</b>. Isinya tampil di menu informasi aplikasi.
</p>

<h2 class="sec">Cara mengubah</h2>
<ol class="steps">
    <li>Buka <b>App Content</b>. Ada dua editor: <b>Tentang Aplikasi</b> dan <b>Syarat &amp; Ketentuan</b>.</li>
    <li>Tulis/ubah isinya pada editor teks kaya (bisa memakai judul, tebal, daftar, dan gambar).</li>
    <li>Klik <b>Simpan Konten</b>. Perubahan langsung berlaku di aplikasi.</li>
</ol>

<div class="box note">
    <span class="bt">Nama aplikasi TIDAK diatur di sini</span>
    App Content hanya berisi <b>Tentang</b> dan <b>Syarat &amp; Ketentuan</b>. <b>Nama aplikasi</b> (dan onboarding)
    diatur di modul <b>Settings</b>. Meski di sisi aplikasi ketiganya tampil bersama, pengaturannya di modul berbeda.
</div>
<div class="box tip">
    <span class="bt">Judul otomatis</span>
    Judul kedua halaman sudah ditetapkan ("Tentang Aplikasi" dan "Syarat &amp; Ketentuan"). Anda cukup mengisi isinya.
</div>
