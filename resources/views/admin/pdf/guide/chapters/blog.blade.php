    <span class="path">Sidebar → Tampilan Website → Blog</span>
</p>
<p>
    Modul <b>Blog</b> mengelola artikel di situs web — menulis, mengunggah gambar, mengatur kategori, dan menerbitkannya.
</p>

<h2 class="sec">Halaman daftar</h2>
<p>Tabel menampilkan: <b>Thumbnail</b>, <b>Judul</b>, <b>Kategori</b>, <b>Slug</b>, jumlah <b>dilihat</b>, pembuat/pengubah, dan <b>Status</b> (Publish/Unpublish). Pencarian &amp; halaman memakai fitur tabel bawaan.</p>
<div class="box note">
    <span class="bt">Tombol di daftar hanya Edit</span>
    Pada baris daftar hanya tersedia tombol <b>Edit</b>. Membuat artikel baru lewat tombol <b>Tambah</b> di atas.
</div>

<h2 class="sec">Menulis artikel</h2>
<ol class="steps">
    <li>Klik <b>Tambah</b>, isi <b>Judul</b> (maks. 200 karakter).</li>
    <li>Pilih <b>Kategori</b> (harus dibuat lebih dulu — lihat bawah).</li>
    <li>Tulis <b>Konten</b> pada editor teks kaya (bisa sisip gambar), dan unggah <b>Thumbnail</b> (JPG/PNG/WebP/SVG, maks. 2 MB).</li>
    <li>Isi <b>Keywords</b> (kata kunci untuk SEO).</li>
    <li>Pilih <b>Status</b>: <b>Publish</b> (tampil di web) atau <b>Unpublish</b> (draf/sembunyi), lalu simpan.</li>
</ol>

<div class="box warn">
    <span class="bt">Judul menentukan alamat (slug) &amp; harus unik</span>
    Alamat artikel dibuat otomatis dari judul. Judul yang sama dengan artikel lain <b>ditolak</b> (duplikasi slug).
    Mengganti judul artikel yang sudah tayang akan mengubah alamatnya — hindari bila tak perlu.
</div>

<h2 class="sec">Kategori Blog</h2>
<p>
    Sebelum menulis artikel, siapkan <b>kategori</b> lewat submenu <b>Kategori</b> di dalam Blog. Tambah/ubah kategori
    dilakukan lewat jendela (modal): isi <b>Nama</b> dan status <b>Aktif</b>. Hanya kategori <b>Aktif</b> yang muncul
    sebagai pilihan saat menulis artikel.
</p>
<div class="box note">
    <span class="bt">Hati-hati menghapus kategori</span>
    Kategori yang masih dipakai artikel sebaiknya tidak dihapus, karena artikel merujuk ke kategori tersebut.
</div>
