<p>
    Modul <b>Banner</b> mengelola gambar banner/slider yang tampil di <b>situs web</b>. Tiap banner terdiri dari
    gambar, judul, dan subjudul.
</p>

<h2 class="sec">Halaman daftar</h2>
<p>Tabel menampilkan: <b>Gambar</b>, <b>Judul</b>, <b>Subjudul</b>, <b>Dibuat/Diperbarui oleh</b>, dan <b>Status</b> (Aktif/Tidak Aktif). Pencarian bekerja pada subjudul, pembuat/pengubah, dan status.</p>

<h2 class="sec">Menambah / mengubah banner</h2>
<ol class="steps">
    <li>Klik <b>Tambah Banner</b> — form muncul di jendela (modal).</li>
    <li>Unggah <b>gambar</b>, isi <b>Judul</b> dan <b>Subjudul</b> (masing-masing 3–200 karakter).</li>
    <li>Pilih <b>Status</b> (Aktif / Tidak Aktif), lalu klik simpan.</li>
</ol>
<p>Edit dan hapus dilakukan lewat ikon pada tiap baris. Penghapusan meminta konfirmasi dan menghapus file gambarnya.</p>

<div class="box note">
    <span class="bt">Yang bisa &amp; tidak bisa diatur</span>
    Banner hanya menyimpan <b>gambar + judul + subjudul + status</b>. Modul ini <b>belum</b> memiliki pengaturan
    <b>urutan</b>, <b>tautan/tombol</b>, atau <b>periode tayang</b>. Untuk menyembunyikan banner, cukup ubah statusnya
    menjadi Tidak Aktif.
</div>
<div class="box tip">
    <span class="bt">Batalkan unggahan yang belum disimpan</span>
    Bila Anda sudah mengunggah gambar lalu menutup form tanpa menyimpan, sistem menawarkan untuk membersihkan file sementara
    agar tidak menumpuk.
</div>
