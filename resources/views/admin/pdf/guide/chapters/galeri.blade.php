<p>
    Modul <b>Galeri</b> mengelola entri bergambar untuk situs web. Meski bernama "galeri", tiap entri sebenarnya
    berupa <b>satu gambar disertai judul dan konten</b> (seperti artikel bergambar) — bukan album banyak foto.
</p>

<h2 class="sec">Halaman daftar</h2>
<p>Kolom: <b>Gambar</b>, <b>Judul</b>, <b>Slug</b>, <b>Dibuat/Diperbarui oleh</b>, dan <b>Status</b>. Pencarian bekerja pada slug, pembuat/pengubah, dan status.</p>

<h2 class="sec">Menambah / mengubah galeri</h2>
<ol class="steps">
    <li>Klik <b>Tambah Galeri</b> — form muncul di jendela (modal).</li>
    <li>Unggah <b>gambar</b>, isi <b>Judul</b>, dan tulis <b>Konten</b> pada editor teks kaya (bisa sisip gambar).</li>
    <li>Isi <b>Keywords</b> (kata kunci) — <b>minimal satu</b>.</li>
    <li>Pilih <b>Status</b> (Aktif / Tidak Aktif), lalu simpan.</li>
</ol>

<div class="box warn">
    <span class="bt">Keywords wajib diisi</span>
    Kosongkan Keywords dapat menyebabkan penyimpanan gagal. Selalu isi minimal satu kata kunci.
</div>
<div class="box note">
    <span class="bt">Slug mengikuti judul</span>
    Alamat (slug) dibuat otomatis dari judul dan diperbarui setiap kali judul diubah — hindari sering mengganti judul
    entri yang sudah tayang agar tautannya tetap.
</div>
