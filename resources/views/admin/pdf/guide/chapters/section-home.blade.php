<p>
    <b>Section Home</b> adalah <b>penyusun beranda aplikasi</b>. Admin membuat blok-blok (section) yang tampil di halaman
    utama aplikasi — misalnya "Produk Terbaru", "Layanan Unggulan", atau "Voucher Aktif" — lengkap dengan sumber data,
    tata letak, dan urutannya.
</p>

<h2 class="sec">Halaman daftar</h2>
<p>Tiap section ditampilkan dengan kolom: <b>Urutan</b> (tombol naik/turun), <b>Section</b> (judul), <b>Sumber</b>, <b>Layout</b>, <b>Data</b> (manual/otomatis), <b>Maks</b> item, dan <b>Status</b>.</p>

<h2 class="sec">Membuat section</h2>
<ol class="steps">
    <li>Klik <b>Tambah Section</b>, isi <b>Judul</b> dan subjudul (opsional).</li>
    <li>Pilih <b>Sumber Data</b>: Produk, Layanan, Voucher, Inspirasi, atau Blog.</li>
    <li>Pilih <b>Layout</b>: <b>Slider</b> (geser horizontal), <b>List</b> (vertikal), atau <b>Grid</b>.</li>
    <li>Pilih <b>Cara Pilih Data</b>:
        <b>Otomatis</b> (berdasarkan aturan/filter) atau <b>Manual</b> (pilih item sendiri).</li>
    <li>Atur <b>Maks item</b> (1–50) dan <b>target "Lihat Semua"</b> bila perlu, lalu simpan.</li>
</ol>

<h2 class="sec">Otomatis vs Manual</h2>
<table class="tbl">
    <tr><th style="width:130px;">Mode</th><th>Cara kerja</th></tr>
    <tr><td><b>Otomatis</b></td><td>Item terisi sendiri menurut <b>Filter</b> yang dipilih (mis. Produk: Terbaru, Diskon, Populer, Unggulan, Rating Tertinggi; Layanan: Terbaru, Populer, Unggulan, Segera Hadir; Voucher: Aktif/Terbaru).</td></tr>
    <tr><td><b>Manual</b></td><td>Admin memilih item satu per satu. <b>Urutan pemilihan = urutan tampil</b> di aplikasi.</td></tr>
</table>

<div class="box warn">
    <span class="bt">Ganti mode/sumber menghapus pilihan manual</span>
    Mengubah mode dari <b>Manual</b> ke <b>Otomatis</b> akan <b>menghapus semua item manual</b>. Mengganti Sumber Data
    saat mode manual juga mereset pilihan item. Tetapkan sumber dan mode dulu sebelum memilih item.
</div>

<h2 class="sec">Mengurutkan section</h2>
<p>Gunakan tombol <b>panah naik/turun</b> pada kolom Urutan untuk memindahkan posisi section di beranda. Halaman akan dimuat ulang setiap kali diurutkan.</p>

<div class="box note">
    <span class="bt">Filter wajib untuk mode Otomatis</span>
    Section bermode <b>Otomatis</b> wajib memilih <b>Filter</b> yang valid untuk sumbernya, jika tidak penyimpanan ditolak.
    Sumber "Paket" masih dinonaktifkan (belum tersedia).
</div>
