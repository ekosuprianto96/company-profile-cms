<p>
    <span class="path">Sidebar → Pengaturan → Modul</span>
</p>
<p>
    Modul <b>Modul (Modules)</b> mengatur <b>pengelompokan menu dashboard</b>. Struktur menu dashboard tersusun berlapis:
    <b>Grup → Modul → Menu</b>. Grup mengelompokkan beberapa modul; modul mengelompokkan beberapa item menu.
</p>

<div class="box note">
    <span class="bt">Fitur teknis — jarang diubah harian</span>
    Modul ini untuk <b>menata struktur menu</b> dashboard, biasanya dilakukan sekali saat penyiapan. Admin operasional
    umumnya tidak perlu menyentuhnya.
</div>

<h2 class="sec">Halaman daftar</h2>
<p>Tabel menampilkan: <b>Nama</b> modul, <b>Group</b> induknya, <b>Jumlah Menu</b> di dalamnya, dan <b>Status</b> (Aktif/Tidak Aktif).</p>

<h2 class="sec">Menambah / mengubah modul</h2>
<ol class="steps">
    <li>Klik <b>Tambah Module</b> (form muncul di jendela).</li>
    <li>Isi <b>Nama</b>, pilih <b>Ikon</b>, pilih <b>Group</b> induk, tulis <b>Keterangan</b>, dan atur <b>Status</b>.</li>
    <li>Klik simpan.</li>
</ol>

<div class="box note">
    <span class="bt">Alamat menu diatur terpisah</span>
    Form modul tidak berisi kolom <b>URL</b> atau <b>urutan</b>. Modul hanya lapisan pengelompokan; tautan tiap item menu
    (URL) dikelola pada pengaturan menu, bukan di sini.
</div>
<div class="box warn">
    <span class="bt">Menonaktifkan modul menyembunyikan menunya</span>
    Mengubah status modul menjadi Tidak Aktif dapat menyembunyikan menu-menu di bawahnya dari sidebar. Ubah dengan hati-hati.
</div>
